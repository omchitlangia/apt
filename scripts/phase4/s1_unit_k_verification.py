# 1c(a) — exit-reason mix + share of net per reason (kalman vs frozen)
# ----------------------------------------------------------------------
def exit_reason_mix(kt: pd.DataFrame, ft: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for name, t in (("kalman", kt), ("frozen_ou", ft)):
        tot_net = t.net_log_pnl.sum()
        for reason in FIVE_CATEGORY_EXIT_REASONS + ("__OTHER__",):
            sub = t[t.exit_canon == reason]
            if sub.empty and reason == "__OTHER__":
                continue
            rows.append(
                {
                    "engine": name,
                    "exit_reason": reason,
                    "n_trades": int(sub.shape[0]),
                    "share_of_trades": sub.shape[0] / max(t.shape[0], 1),
                    "net_log_pnl_sum": sub.net_log_pnl.sum(),
                    "share_of_net": (sub.net_log_pnl.sum() / tot_net) if tot_net != 0 else np.nan,
                }
            )
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "1c_a_exit_reason_mix.csv", index=False)
    return df


