# 1c(b) — per-trade net P&L distribution (kalman vs frozen)
# ----------------------------------------------------------------------
def per_trade_dist(kt: pd.DataFrame, ft: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for name, t in (("kalman", kt), ("frozen_ou", ft)):
        v = t.net_log_pnl.to_numpy()
        g = t.gross_log_pnl.to_numpy()
        rows.append(
            {
                "engine": name,
                "n_trades": int(v.size),
                "net_mean_bps": float(np.mean(v) * 1e4),
                "net_median_bps": float(np.median(v) * 1e4),
                "net_p5_bps": float(np.percentile(v, 5) * 1e4),
                "net_p95_bps": float(np.percentile(v, 95) * 1e4),
                "net_worst_bps": float(np.min(v) * 1e4),
                "gross_mean_bps": float(np.mean(g) * 1e4),
                "win_rate_net": float(np.mean(v > 0)),
            }
        )
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "1c_b_per_trade_dist.csv", index=False)
    return df


# ----------------------------------------------------------------------
# 1c(c) — overlap: fraction of kalman gross accrued in windows where the
# frozen arm held a losing time_stop/fold_close position (same pair-fold)
# ----------------------------------------------------------------------
def overlap_fraction(ft: pd.DataFrame) -> pd.DataFrame:
    ps = pd.read_csv(KALMAN / "pair_sessions_kalman.csv")
    ps = ps[(ps.freq_min == BEST_FREQ) & (ps.spread_bps == BEST_COST)].copy()
    ps["date"] = pd.to_datetime(ps.date).dt.date

    # frozen losing time_stop / fold_close windows, per pair-fold
    loser = ft[(ft.exit_canon.isin(["time_stop", "fold_close"])) & (ft.net_log_pnl < 0)].copy()
    loser["entry_d"] = pd.to_datetime(loser.entry_ts).dt.date
    loser["exit_d"] = pd.to_datetime(loser.exit_ts).dt.date

    rows = []
    total_gross = ps.gross_log_ret.sum()
    in_window_gross = 0.0
    for (fid, pair), grp in ps.groupby(["fold_id", "pair"]):
        wins = loser[(loser.fold_id == fid) & (loser.pair == pair)]
        mask = pd.Series(False, index=grp.index)
        for _, w in wins.iterrows():
            mask |= (grp.date >= w.entry_d) & (grp.date <= w.exit_d)
        g_in = grp.loc[mask, "gross_log_ret"].sum()
        g_all = grp.gross_log_ret.sum()
        in_window_gross += g_in
        rows.append(
            {
                "fold_id": fid,
                "pair": pair,
                "n_frozen_losing_timestop_foldclose": int(wins.shape[0]),
                "kalman_gross_in_window": g_in,
                "kalman_gross_total_pairfold": g_all,
                "fraction_in_window": (g_in / g_all) if g_all != 0 else np.nan,
            }
        )
    rows.append(
        {
            "fold_id": "ALL",
            "pair": "ALL",
            "n_frozen_losing_timestop_foldclose": int(loser.shape[0]),
            "kalman_gross_in_window": in_window_gross,
            "kalman_gross_total_pairfold": total_gross,
            "fraction_in_window": (in_window_gross / total_gross) if total_gross != 0 else np.nan,
        }
    )
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "1c_c_overlap.csv", index=False)
    return df


# ----------------------------------------------------------------------
# 1c(d) — mu_t tracking: total |Delta mu| in sigma_eq units + profit-
# truncation-by-tracking (only INDUSINDBK fold4 overlay is persisted +
# traded; KOTAK overlay was NOT persisted -> [TODO data]).
# ----------------------------------------------------------------------
def mu_tracking(kt: pd.DataFrame) -> pd.DataFrame:
    rows = []
    # INDUSINDBK fold4 f5 — traded survivor with persisted overlay
    ov_path = KALMAN / "mu_overlay_INDUSINDBK_HDFCBANK_fold4_f5.csv"
    ov = pd.read_csv(ov_path)
    ov["ts"] = pd.to_datetime(ov.ts)
    pf_trades = kt[(kt.fold_id == 4) & (kt.pair == "INDUSINDBK/HDFCBANK")].copy()
    pf_trades["entry_ts"] = pd.to_datetime(pf_trades.entry_ts)
    pf_trades["exit_ts"] = pd.to_datetime(pf_trades.exit_ts)

    # recover sigma_eq_resid from the entry identity z = (spread - mu)/sigma_eq
    sig_est = []
    for _, tr in pf_trades.iterrows():
        m = ov[ov.ts == tr.entry_ts]
        if not m.empty and tr.z_entry != 0:
            sig_est.append((m.spread.iloc[0] - m.mu_kalman.iloc[0]) / tr.z_entry)
    sigma_eq_resid = float(np.median(sig_est)) if sig_est else np.nan

    # per-session mu path -> total |Delta mu|
    ov["date"] = ov.ts.dt.date
    sess_mu = ov.groupby("date").mu_kalman.first()
    total_abs_dmu = float(np.abs(np.diff(sess_mu.to_numpy())).sum())
    total_abs_dmu_sigeq = total_abs_dmu / sigma_eq_resid if sigma_eq_resid else np.nan

    # profit-truncation: did mu move TOWARD the entry spread during holding?
    n_trunc, n_tot = 0, 0
    for _, tr in pf_trades.iterrows():
        me = ov[ov.ts == tr.entry_ts]
        mx = ov[ov.ts == tr.exit_ts]
        if me.empty or mx.empty:
            continue
        n_tot += 1
        mu0, mu1 = me.mu_kalman.iloc[0], mx.mu_kalman.iloc[0]
        entry_spread = me.spread.iloc[0]
        # mu moved toward entry spread if |mu1 - entry_spread| < |mu0 - entry_spread|
        if abs(mu1 - entry_spread) < abs(mu0 - entry_spread):
            n_trunc += 1
    rows.append(
        {
            "fold_id": 4,
            "pair": "INDUSINDBK/HDFCBANK",
            "freq_min": 5,
            "traded": True,
            "sigma_eq_resid_recovered": sigma_eq_resid,
            "total_abs_dmu_log": total_abs_dmu,
            "total_abs_dmu_sigma_eq": total_abs_dmu_sigeq,
            "n_trades": n_tot,
            "n_trades_anchor_moved_toward_entry": n_trunc,
            "frac_trunc": (n_trunc / n_tot) if n_tot else np.nan,
        }
    )

    # fold6 INDUSINDBK (diagnostic, NOT traded) — overlay persisted but no
    # trades -> report total |Delta mu| in log units; sigma_eq + truncation
    # are [TODO data] (no trades to recover sigma_eq from; KOTAK overlay
    # was never persisted by the Unit-K run).
    ov6 = pd.read_csv(KALMAN / "mu_overlay_INDUSINDBK_HDFCBANK_fold6_f5.csv")
    ov6["date"] = pd.to_datetime(ov6.ts).dt.date
    sess_mu6 = ov6.groupby("date").mu_kalman.first()
    rows.append(
        {
            "fold_id": 6,
            "pair": "INDUSINDBK/HDFCBANK",
            "freq_min": 5,
            "traded": False,
            "sigma_eq_resid_recovered": np.nan,  # [TODO data] no trades
            "total_abs_dmu_log": float(np.abs(np.diff(sess_mu6.to_numpy())).sum()),
            "total_abs_dmu_sigma_eq": np.nan,  # [TODO data]
            "n_trades": 0,
            "n_trades_anchor_moved_toward_entry": 0,
            "frac_trunc": np.nan,
        }
    )
    rows.append(
        {
            "fold_id": 6,
            "pair": "KOTAKBANK/HDFCBANK",
            "freq_min": 5,
            "traded": True,
            "sigma_eq_resid_recovered": np.nan,  # [TODO data] overlay not persisted
            "total_abs_dmu_log": np.nan,
            "total_abs_dmu_sigma_eq": np.nan,
            "n_trades": int(kt[(kt.fold_id == 6) & (kt.pair == "KOTAKBANK/HDFCBANK")].shape[0]),
            "n_trades_anchor_moved_toward_entry": -1,  # sentinel: not computable
            "frac_trunc": np.nan,
        }
    )
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "1c_d_mu_tracking.csv", index=False)
    return df, sigma_eq_resid, ov, pf_trades


