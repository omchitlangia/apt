def _trade_counts(path: Path, freq: int, cost: int, extra: dict) -> int:
    t = pd.read_csv(path)
    m = (t.freq_min == freq) & (t.spread_bps == cost)
    for k, v in extra.items():
        m &= t[k] == v
    t = t[m]
    t = t[t.apply(lambda r: (r.fold_id, r.pair) in MATCHED, axis=1)]
    return int(t.shape[0])


def eight_cell_table() -> pd.DataFrame:
    """All three engines on the MATCHED 2 pair-folds, recomputed from the
    persisted per-session returns (self-consistent, full metric set)."""
    ps_k = pd.read_csv(KALMAN / "pair_sessions_kalman.csv")
    ps_o = pd.read_csv(OU / "pair_sessions_ou.csv")
    ps_r = pd.read_csv(OU / "pair_sessions_rolling_baseline.csv")
    rows = []
    for freq in (5, 15):
        for cost in (1, 3, 5, 8):
            k = _matched_portfolio_metrics(
                ps_k[(ps_k.freq_min == freq) & (ps_k.regime == "B") & (ps_k.spread_bps == cost)]
            )
            o = _matched_portfolio_metrics(
                ps_o[
                    (ps_o.freq_min == freq)
                    & (ps_o.regime == "B")
                    & (ps_o.spread_bps == cost)
                    & (ps_o.stop_mode == "none")
                ]
            )
            r = _matched_portfolio_metrics(
                ps_r[(ps_r.freq_min == freq) & (ps_r.regime == "B") & (ps_r.spread_bps == cost)]
            )
            row = {"freq_min": freq, "cost_bps": cost}
            row.update(
                {
                    "k_n_trades": _trade_counts(KALMAN / "trades_kalman.csv", freq, cost, {}),
                    "ou_n_trades": _trade_counts(
                        OU / "trades_ou.csv", freq, cost, {"regime": "B", "stop_mode": "none"}
                    ),
                    "rz_n_trades": _trade_counts(
                        OU / "trades_rolling_baseline.csv", freq, cost, {"regime": "B"}
                    ),
                }
            )
            for pre, m in (("k", k), ("ou", o), ("rz", r)):
                row[f"{pre}_gross_total_pct"] = m["gross_total_pct"]
                row[f"{pre}_net_total_pct"] = m["net_total_pct"]
                row[f"{pre}_gross_sharpe"] = m["gross_sharpe"]
                row[f"{pre}_net_sharpe"] = m["net_sharpe"]
                row[f"{pre}_net_ann_pct"] = m["net_ann_pct"]
                row[f"{pre}_net_maxDD_pct"] = m["net_maxDD_pct"]
            rows.append(row)
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "1b_eight_cell_table.csv", index=False)

    # cross-check vs persisted matched_metrics.csv (OU + rolling_z net%)
    mm = pd.read_csv(OU / "figures/matched_universe/matched_metrics.csv")
    chk = []
    for _, mrow in mm.iterrows():
        pre = {"ou": "ou", "rolling_z": "rz"}.get(mrow.engine)
        if pre is None:
            continue
        ours = df[(df.freq_min == mrow.freq_min) & (df.cost_bps == mrow.spread_bps)]
        if ours.empty:
            continue
        chk.append(abs(float(ours[f"{pre}_net_total_pct"].iloc[0]) - mrow.net_total_pct))
    print(f"[1b] matched cross-check vs matched_metrics.csv: max |Δnet%| = {max(chk):.4f}")
    print(f"[1b] wrote full 8-cell table: {df.shape[0]} cells x kalman/frozen/rolling (matched)")
    return df


