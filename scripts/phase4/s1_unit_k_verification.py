def admissible_denominator() -> pd.DataFrame:
    st = pd.read_csv(KALMAN / "selection_table.csv")
    ss = pd.read_csv(KALMAN / "selection_summary.csv")
    # denominator = distinct (fold_id, pair, freq) survivor rows at any H
    keys = st[["fold_id", "pair", "freq_min"]].drop_duplicates()
    n_pairfolds = st[["fold_id", "pair"]].drop_duplicates().shape[0]
    n_freqs = st.freq_min.nunique()
    df = pd.DataFrame(
        [
            {
                "denominator_meaning": "distinct (pair-fold x freq) survivor units scored per H",
                "n_pairfold_x_freq": int(keys.shape[0]),
                "n_distinct_pairfolds": int(n_pairfolds),
                "n_freqs": int(n_freqs),
                "decomposition": f"{n_pairfolds} pair-folds x {n_freqs} freqs = {keys.shape[0]}",
                "n_total_in_summary_chosen_H": int(ss[ss.chosen].n_total.iloc[0]),
                "n_admissible_chosen_H": int(ss[ss.chosen].n_admissible.iloc[0]),
            }
        ]
    )
    df.to_csv(OUT / "1d_admissible_denominator.csv", index=False)
    return df


