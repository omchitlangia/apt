    for ax, freq in zip(axes, (5, 15), strict=True):
        sub = tbl[tbl.freq_min == freq].sort_values("cost_bps")
        ax.plot(sub.cost_bps, sub.k_net_sharpe, "o-", label="kalman")
        ax.plot(sub.cost_bps, sub.ou_net_sharpe, "s-", label="frozen-OU")
        ax.plot(sub.cost_bps, sub.rz_net_sharpe, "^-", label="rolling_z")
        ax.set_title(f"net Sharpe vs cost — f{freq} / B")
        ax.set_xlabel("cost (bps)")
        ax.set_ylabel("net Sharpe")
        ax.legend(fontsize=8)
    savefig_with_csv(fig, FIG / "d_cost_ladder_3engine.png", tbl)
    plt.close(fig)


