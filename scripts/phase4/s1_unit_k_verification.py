def fig_exit_stacked(mix: pd.DataFrame) -> None:
    piv = mix.pivot_table(index="engine", columns="exit_reason", values="n_trades", fill_value=0)
    cats = [c for c in FIVE_CATEGORY_EXIT_REASONS if c in piv.columns]
    fig, ax = plt.subplots(figsize=(7, 4))
    bottom = np.zeros(len(piv))
    for c in cats:
        ax.bar(piv.index, piv[c], bottom=bottom, label=c)
        bottom += piv[c].to_numpy()
    ax.set_ylabel("n_trades")
    ax.set_title("h: exit-reason mix — kalman_mu vs frozen-OU (5min / B / 3bps)")
    ax.legend(fontsize=8)
    savefig_with_csv(fig, FIG / "h_exit_reason_stacked.png", mix)
    plt.close(fig)


def fig_pnl_dist(kt: pd.DataFrame, ft: pd.DataFrame) -> None:
    fig, ax = plt.subplots(figsize=(7, 4))
    bins = np.linspace(-0.05, 0.12, 40)
    ax.hist(kt.net_log_pnl, bins=bins, alpha=0.6, label=f"kalman (n={kt.shape[0]})")
    ax.hist(ft.net_log_pnl, bins=bins, alpha=0.6, label=f"frozen (n={ft.shape[0]})")
    ax.axvline(0, color="k", lw=0.8)
    ax.set_xlabel("net log P&L per trade")
    ax.set_title("per-trade net P&L — kalman vs frozen (5min / B / 3bps)")
    ax.legend()
    data = pd.concat(
        [
            kt[["net_log_pnl"]].assign(engine="kalman"),
            ft[["net_log_pnl"]].assign(engine="frozen_ou"),
        ]
    )
    savefig_with_csv(fig, FIG / "per_trade_pnl_dist.png", data)
    plt.close(fig)


