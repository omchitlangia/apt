# 1e — reviewer pre-registered predictions
# ----------------------------------------------------------------------
def predictions(kt: pd.DataFrame, mix: pd.DataFrame, overlap: pd.DataFrame) -> pd.DataFrame:
    km = pd.read_csv(KALMAN / "metrics_kalman.csv")
    ou = pd.read_csv(OU / "metrics_ou.csv")
    kbest = km[(km.freq_min == BEST_FREQ) & (km.spread_bps == BEST_COST)].iloc[0]
    obest = ou[
        (ou.freq_min == BEST_FREQ)
        & (ou.regime == "B")
        & (ou.spread_bps == BEST_COST)
        & (ou.stop_mode == "none")
    ].iloc[0]

    mr_share = mix[
        (mix.engine == "kalman") & (mix.exit_reason == "mean_revert")
    ].share_of_trades.iloc[0]
    avg_capture_bps = float(kt.gross_log_pnl.mean() * 1e4)
    overlap_all = overlap[overlap.fold_id == "ALL"].fraction_in_window.iloc[0]
    k_maxdd = float(kbest.net_max_drawdown_pct)
    o_maxdd = float(obest.net_max_drawdown_pct)

    rows = [
        {
            "prediction": ">=80% mean_revert exits (best cell)",
            "metric": mr_share,
            "threshold": 0.80,
            "verdict": "MET" if mr_share >= 0.80 else "NOT MET",
        },
        {
            "prediction": "avg gross capture 200-260 bps/trade",
            "metric": avg_capture_bps,
            "threshold": "[200,260]",
            "verdict": "MET" if 200 <= avg_capture_bps <= 260 else "NOT MET",
        },
        {
            "prediction": "majority of kalman gross in frozen losing time_stop/fold_close windows",
            "metric": overlap_all,
            "threshold": 0.50,
            "verdict": "MET" if overlap_all > 0.50 else "NOT MET",
        },
        {
            "prediction": "kalman max_DD better than frozen -22%",
            "metric": k_maxdd,
            "threshold": o_maxdd,
            "verdict": "MET" if k_maxdd > o_maxdd else "NOT MET",
        },
    ]
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "1e_predictions.csv", index=False)
    return df


