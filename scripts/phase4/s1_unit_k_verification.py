# The matched universe: the 2 pair-folds that survive the OU static-HL gate.
MATCHED = {(4, "INDUSINDBK/HDFCBANK"), (6, "KOTAKBANK/HDFCBANK")}


def _matched_portfolio_metrics(ps: pd.DataFrame) -> dict:
    """Equal-notional portfolio metrics on the matched 2 pair-folds.

    Reaggregates persisted per-session returns (groupby date, mean across
    pairs) and runs ``compute_metrics`` — NOT a strategy re-run.
    """
    ps = ps[ps.apply(lambda r: (r.fold_id, r.pair) in MATCHED, axis=1)]
    port = ps.groupby("date").agg(
        gross_log_ret=("gross_log_ret", "mean"),
        net_log_ret=("net_log_ret", "mean"),
    )
    mg = compute_metrics(port.gross_log_ret.to_numpy())
    mn = compute_metrics(port.net_log_ret.to_numpy())
    return {
        "n_sessions": int(port.shape[0]),
        "gross_total_pct": mg["total_return_pct"],
        "net_total_pct": mn["total_return_pct"],
        "gross_ann_pct": mg["ann_return_pct"],
        "net_ann_pct": mn["ann_return_pct"],
        "gross_sharpe": mg["sharpe"],
        "net_sharpe": mn["sharpe"],
        "net_maxDD_pct": mn["max_drawdown_pct"],
    }


